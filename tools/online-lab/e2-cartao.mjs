// Cartão do jogador e campos de dinheiro em 380 px.  npx vite --port 4173 --strictPort ; cd tools/online-lab && node e2-cartao.mjs
import { chromium } from 'playwright'
import { resolve } from 'node:path'
const base = process.argv[2] ?? 'http://localhost:4173'
const shots = resolve('../../.shots')
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 380, height: 844 }, deviceScaleFactor: 2, locale: 'pt-BR' })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('[erro]', e.message))
await page.goto(`${base}/?time=imp&semente=7&tela=squad`)
await page.getByRole('dialog').first().waitFor({ state: 'detached', timeout: 1 }).catch(() => {})
await page.waitForSelector('ul li button', { timeout: 90000 })
await page.locator('ul li button').first().click()
await page.getByTestId('player-card').waitFor({ timeout: 30000 })
const shot = (n) => page.screenshot({ path: resolve(shots, `e2-${n}.png`) })
await shot('cartao')
await page.getByTestId('shirt-number').click()
await shot('camisa')
await page.getByRole('textbox', { name: 'Número da camisa' }).fill('77')
await page.getByRole('button', { name: 'Salvar' }).click()
console.log('camisa:', (await page.getByTestId('shirt-number').innerText()).replace(/\s+/g, ' '))
await page.getByRole('button', { name: 'Renovar', exact: true }).click()
await page.waitForTimeout(300)
const money = page.locator('input[inputmode="numeric"]').first()
await money.fill('')
await money.pressSequentially('5608000')
console.log('digitado 5608000 ->', await money.inputValue())
await shot('renovar')
await page.getByRole('button', { name: 'Treino', exact: true }).click()
await shot('treino')
await page.getByRole('button', { name: 'Mercado', exact: true }).click()
await shot('mercado')
await page.getByRole('button', { name: 'Lista de transferências' }).click()
await page.waitForTimeout(300)
await shot('anunciar')
await page.getByRole('button', { name: 'Fechar' }).last().click().catch(() => {})
await page.keyboard.press('Escape')
await page.getByRole('button', { name: 'Propostas', exact: true }).click().catch(() => {})
await shot('propostas')
await page.getByRole('button', { name: 'Dispensar', exact: true }).click().catch(() => {})
await shot('dispensar')
await page.getByTestId('toggle-numbers').click().catch(() => {})
await page.evaluate(() => document.querySelector('[data-testid=toggle-numbers]')?.scrollIntoView())
await shot('numeros')
await browser.close()
